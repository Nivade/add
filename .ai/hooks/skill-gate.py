    ("backend/app/Contracts/AiProvider.php", ["ai-layer-changes"], ["ai-layer.md"]),
    ("backend/config/ai.php", ["ai-layer-changes"], ["ai-layer.md"]),
    ("backend/app/Enums/Ai/", ["ai-layer-changes"], ["ai-layer.md"]),
