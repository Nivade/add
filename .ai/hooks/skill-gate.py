    ("backend/tests/", ["pest-testing", "testing-best-practices"], ["testing.md"]),
    ("backend/app/Data/", ["laravel-data"], ["api-and-data.md"]),
    ("backend/app/Http/", ["laravel-attributes"], ["api-and-data.md"]),
    ("backend/routes/api.php", [], ["api-and-data.md"]),
    ("backend/app/Actions/Calendar/", ["calendar-sync", "laravel-actions"], ["domain-model.md"]),
    ("backend/app/Actions/", ["laravel-actions"], ["domain-model.md"]),
    ("backend/app/Models/", ["laravel-attributes"], ["domain-model.md"]),
